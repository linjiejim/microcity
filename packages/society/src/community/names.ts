const cohort = (age: number): number => (age >= 60 ? 0 : age >= 38 ? 1 : age >= 16 ? 2 : 3);

export const surnameFor = (seed: number, key: string): string => SURNAMES[Math.floor(rand(seed, 'surname', key) * SURNAMES.length)]!;

export function givenFor(seed: number, key: string, gender: 'f' | 'm', age: number, attempt = 0): string {
  const list = GIVEN[gender][cohort(age)]!;
  return list[Math.floor(rand(seed, 'given', key, attempt) * list.length)]!;
}
